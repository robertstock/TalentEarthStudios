import assert from 'node:assert/strict';
import { randomUUID, createHmac } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { PrismaClient } from '@prisma/client';
const base = process.env.MOBILE_TEST_URL || 'http://localhost:3016';
if (!['localhost','127.0.0.1'].includes(new URL(base).hostname) || new URL(process.env.DATABASE_URL).hostname !== '127.0.0.1') throw new Error('Integration tests require an isolated localhost database and server.');
const db = new PrismaClient();
const secret = 'isolated-mobile-test-secret-not-production';
const mail = () => readFileSync('/private/tmp/talentearth-mobile-test-mail.jsonl','utf8').trim().split('\n').map(line=>JSON.parse(line));
let checks=0;
function check(value,expected,label){assert.deepEqual(value,expected,label);checks++;console.log(`PASS ${label}`);}
async function req(path,{data,token,method,form,origin}={}) {
 const response = await fetch(`${base}/api/mobile${path}`,{method:method||(data||form?'POST':'GET'),headers:{...(data?{'Content-Type':'application/json'}:{}),...(token?{Authorization:`Bearer ${token}`} : {}),...(origin?{Origin:origin}:{})},body:form||(data?JSON.stringify(data):undefined)});
 return {status:response.status,body:await response.json()};
}
try {
 check((await req('/account')).status,401,'anonymous account access rejected');
 check((await req('/projects',{data:{}})).status,401,'anonymous project submission rejected');
 check((await req('/auth/code',{data:{email:'bad',name:'Test'}})).status,400,'invalid email rejected');
 check((await req('/auth/code',{data:{email:'person@example.test',name:'Test'},origin:'https://untrusted.example'})).status,403,'untrusted web origin rejected');
 const email=`integration-${Date.now()}@example.test`;
 const issued=await req('/auth/code',{data:{email,name:'Ada Test'}});
 check(issued.status,200,'registration sends verification code through provider');
 check(await db.mobileAccount.count({where:{email}}),0,'account not created before email verification');
 const code=mail().filter(item=>item.to===email).at(-1).text.match(/code is (\d{6})/)[1];
 check((await req('/auth/code',{data:{email,name:'Ada Test'}})).status,429,'resend throttle enforced');
 check((await req('/auth/verify',{data:{challengeId:issued.body.challengeId,code:code==='000000'?'000001':'000000'}})).status,400,'wrong code rejected');
 const verified=await req('/auth/verify',{data:{challengeId:issued.body.challengeId,code}});
 check(verified.status,200,'valid email code creates session');
 check(verified.body.account.name,'Ada Test','verified name returned');
 const token=verified.body.token;
 check((await req('/auth/verify',{data:{challengeId:issued.body.challengeId,code}})).status,400,'used code cannot be replayed');
 check((await req('/account',{token})).body.account.email,email,'session restores verified account');
 check(await db.user.count({where:{email}}),0,'mobile signup grants no staff or talent account');
 const challengeId=randomUUID();
 await db.mobileChallenge.create({data:{id:challengeId,email:'attempts@example.test',name:'Attempts',codeHash:createHmac('sha256',secret).update(`${challengeId}:123456`).digest('hex'),expiresAt:new Date(Date.now()+600000)}});
 for(let i=0;i<5;i++) await req('/auth/verify',{data:{challengeId,code:'111111'}});
 check((await req('/auth/verify',{data:{challengeId,code:'123456'}})).status,400,'five wrong attempts lock challenge');
 const expiredId=randomUUID();
 await db.mobileChallenge.create({data:{id:expiredId,email:'expired@example.test',name:'Expired',codeHash:createHmac('sha256',secret).update(`${expiredId}:123456`).digest('hex'),expiresAt:new Date(Date.now()-1000)}});
 check((await req('/auth/verify',{data:{challengeId:expiredId,code:'123456'}})).status,400,'expired verification code rejected');
 await db.user.upsert({where:{email:'local-admin@example.test'},update:{},create:{email:'local-admin@example.test',firstName:'Local',lastName:'Admin',role:'ADMIN',status:'APPROVED'}});
 const project={submissionId:randomUUID(),name:'Integration launch film',summary:'A 30-second launch film featuring the coffee shop. Budget is still undecided.',transcript:'We need a coffee shop film. Budget not decided.'};
 const submissions=await Promise.all([req('/projects',{token,data:project}),req('/projects',{token,data:project})]);
 check(submissions.map(item=>item.status),[200,200],'simultaneous submission retries both succeed');
 check(submissions[0].body.projectId,submissions[1].body.projectId,'retries return the same project');
 const saved=await db.project.findUnique({where:{id:submissions[0].body.projectId},include:{sows:true,meetingNotes:true,client:true,mobileSubmission:true}});
 check(saved.status,'SOW_DRAFT','project appears in existing Incoming status filter');
 check(saved.sows[0].bodyRichText,project.summary,'existing SOW editor receives editable customer brief');
 check(saved.meetingNotes[0].content,project.transcript,'original transcript preserved');
 check(saved.client.email,email,'contact comes from verified account');
 check(saved.isAutoRouted,false,'new project waits for owner review');
 check(await db.project.count({where:{name:project.name}}),1,'only one project created');
 const form=new FormData();form.append('audio',new Blob([new Uint8Array(2048)],{type:'audio/mp4'}),'test.m4a');form.append('duration','300');
 const analysis=await req('/analyze',{token,form});
 check(analysis.status,200,'multi-minute recording reaches transcription and summary providers');
 check(analysis.body.summarized,true,'summary result is explicitly identified');
 check(analysis.body.name,'Coffee shop launch film','structured provider response returned for review');
 const tooLong=new FormData();tooLong.append('audio',new Blob([new Uint8Array(2048)]),'test.m4a');tooLong.append('duration','900');
 check((await req('/analyze',{token,form:tooLong})).status,400,'overlong recording rejected');
 check((await req('/account',{token,method:'DELETE',data:{confirm:'NO'}})).status,400,'account deletion requires explicit confirmation');
 check((await req('/auth/logout',{token,method:'POST'})).status,200,'sign-out revokes server session');
 check((await req('/account',{token})).status,401,'signed-out token cannot be reused');
 const secondId=randomUUID();await db.mobileChallenge.create({data:{id:secondId,email,name:'Wrong overwrite',codeHash:createHmac('sha256',secret).update(`${secondId}:123456`).digest('hex'),expiresAt:new Date(Date.now()+600000)}});
 const again=await req('/auth/verify',{data:{challengeId:secondId,code:'123456'}});
 check(again.body.account.name,'Ada Test','returning login retains original verified name');
 check((await req('/account',{token:again.body.token,method:'DELETE',data:{confirm:'DELETE'}})).status,200,'account deletion succeeds');
 check((await req('/account',{token:again.body.token})).status,401,'deletion revokes every sign-in');
 check(await db.mobileAccount.count({where:{email}}),0,'deleted account removed from database');
 check(await db.project.count({where:{id:saved.id}}),1,'submitted business project retained as disclosed');
 check(mail().some(item=>item.subject===`New project request: ${project.name}`),true,'project notification reaches email provider');
 console.log(`${checks} integration assertions passed (email and AI providers mocked; real HTTP handlers and isolated PostgreSQL).`);
} finally {await db.$disconnect();}
